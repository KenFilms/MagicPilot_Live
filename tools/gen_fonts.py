#!/usr/bin/env python3
"""
Generates main/fonts.c and main/fonts.h: anti-aliased 4-bit bitmap fonts for the overlay UI.

Source font: Open Sans (variable, SIL Open Font License 1.1, see main/fonts/OFL.txt), from
https://github.com/google/fonts/tree/main/ofl/opensans

Usage:  python3 tools/gen_fonts.py path/to/OpenSans[wdth,wght].ttf
Needs:  pip install freetype-py
"""

import sys
import os
import freetype

ASCII = [chr(c) for c in range(32, 127)]
EXTRA = ["°", "…", "–"]          # degree, ellipsis, en dash

# name, pixel size, weight (300..800), characters
FONTS = [
    ("font_13b", 13, 700, ASCII + EXTRA),
    ("font_15b", 15, 700, ASCII + EXTRA),
    ("font_17b", 17, 700, ASCII + EXTRA),
    ("font_20s", 20, 600, ASCII + EXTRA),
    ("font_23s", 23, 600, ASCII + EXTRA),
    ("font_23b", 23, 800, ASCII + EXTRA),
    ("font_26s", 26, 600, ASCII + EXTRA),
    ("font_29s", 29, 600, ASCII + EXTRA),
    ("font_32s", 32, 600, ASCII + EXTRA),
    ("font_46s", 46, 600, ASCII + EXTRA),
]


def render_font(path, name, px, weight, chars):
    face = freetype.Face(path)
    axes = [a.tag for a in face.get_variation_info().axes]
    coords = [weight if tag == "wght" else 100.0 for tag in axes]
    face.set_var_design_coords(coords)
    face.set_pixel_sizes(0, px)
    glyphs = []
    data = bytearray()
    for ch in sorted(set(chars), key=ord):
        face.load_char(ch, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_LIGHT)
        g = face.glyph
        bm = g.bitmap
        w, h = bm.width, bm.rows
        offset = len(data)
        for y in range(h):
            row = bm.buffer[y * bm.pitch: y * bm.pitch + w]
            nib = [(v * 15 + 127) // 255 for v in row]
            if len(nib) % 2:
                nib.append(0)
            for i in range(0, len(nib), 2):
                data.append(nib[i] | (nib[i + 1] << 4))
        adv16 = int(round(g.advance.x / 64.0 * 16))
        glyphs.append((ord(ch), offset, w, h, g.bitmap_left, g.bitmap_top, adv16))
    m = face.size
    ascent = int(round(m.ascender / 64.0))
    descent = int(round(-m.descender / 64.0))
    line_h = int(round(m.height / 64.0))
    face.load_char("H", freetype.FT_LOAD_RENDER)
    cap_h = face.glyph.bitmap_top
    return glyphs, data, ascent, descent, line_h, cap_h


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)
    path = sys.argv[1]
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "main")
    out_c = ["/* Generated by tools/gen_fonts.py from Open Sans (SIL OFL 1.1, see main/fonts/OFL.txt). Do not edit. */",
             "", '#include "fonts.h"', ""]
    out_h = ["/* Generated by tools/gen_fonts.py. Do not edit. */", "", "#pragma once", "", '#include "gfx.h"', ""]
    for name, px, weight, chars in FONTS:
        glyphs, data, ascent, descent, line_h, cap_h = render_font(path, name, px, weight, chars)
        out_c.append(f"static const uint8_t {name}_bits[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out_c.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        out_c.append("};")
        out_c.append(f"static const gfx_glyph_t {name}_glyphs[{len(glyphs)}] = {{")
        for cp, off, w, h, left, top, adv in glyphs:
            out_c.append(f"    {{0x{cp:04x}, {adv}, {off}, {w}, {h}, {left}, {top}}},")
        out_c.append("};")
        out_c.append(f"const gfx_font_t {name} = {{{name}_bits, {name}_glyphs, {len(glyphs)}, "
                     f"{ascent}, {descent}, {line_h}, {cap_h}}};")
        out_c.append("")
        out_h.append(f"extern const gfx_font_t {name};   /* {px} px, weight {weight} */")
    with open(os.path.join(root, "fonts.c"), "w") as f:
        f.write("\n".join(out_c) + "\n")
    with open(os.path.join(root, "fonts.h"), "w") as f:
        f.write("\n".join(out_h) + "\n")


if __name__ == "__main__":
    main()
